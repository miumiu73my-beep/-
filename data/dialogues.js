function freezeLines(lines = []) {
  return Object.freeze([...lines]);
}

function freezeMonths(months = {}) {
  return Object.freeze(
    Object.fromEntries(
      Object.entries(months).map(([month, lines]) => [month, freezeLines(lines)])
    )
  );
}

function freezeScreens(screens = {}) {
  return Object.freeze(
    Object.fromEntries(
      Object.entries(screens).map(([screen, lines]) => [screen, freezeLines(lines)])
    )
  );
}

function freezeDialogueSet(set) {
  return Object.freeze({
    normal: freezeLines(set.normal),
    morning: freezeLines(set.morning),
    daytime: freezeLines(set.daytime),
    night: freezeLines(set.night),
    weekend: freezeLines(set.weekend),
    date: freezeLines(set.date),
    months: freezeMonths(set.months),
    screens: freezeScreens(set.screens),
  });
}

